test('Pixi inspection closes a failed read before trying the next candidate', async () => {
  const { detectPixiVersion } = await loadInspect();
  const dir = temporaryDirectory('pmjs-game-pixi-read-');
  writeGame(dir);
  const first = path.join(dir, 'js', 'libs', 'pixi.js');
  fs.writeFileSync(path.join(dir, 'js', 'pixi.js'), "PIXI.VERSION = '5.3.0';");
  const open = fs.openSync;
  const read = fs.readSync;
  let failedHandle;
  let closedBeforeFallback = false;
  try {
    fs.openSync = function(file, ...args) {
      if (file === path.join(dir, 'js', 'pixi.js')) {
        assert.throws(() => fs.fstatSync(failedHandle), /EBADF/);
        closedBeforeFallback = true;
      }
      const handle = open.call(fs, file, ...args);
      if (file === first) failedHandle = handle;
      return handle;
    };
    fs.readSync = function(handle, ...args) {
      if (handle === failedHandle && !closedBeforeFallback) throw new Error('read failed');
      return read.call(fs, handle, ...args);
    };
    assert.equal(detectPixiVersion(dir).pixiVersion, '5.3.0');
    assert.equal(closedBeforeFallback, true);
  } finally {
    fs.openSync = open;
    fs.readSync = read;
    if (failedHandle !== undefined) {
      try { fs.closeSync(failedHandle); } catch (error) {
        if (error.code !== 'EBADF') throw error;
      }
    }
  }
});

test('game inspection rejects unknown engines and missing manifests', async () => {
  const { inspectGame, readPluginManifest } = await loadInspect();
  const registry = path.join(__dirname, '..', 'profiles', 'plugin-adapters.json');
  const empty = temporaryDirectory('pmjs-game-empty-');
  fs.mkdirSync(path.join(empty, 'js'), { recursive: true });
  assert.throws(() => inspectGame(empty, registry), /plugin manifest not found/);
  const noEngine = temporaryDirectory('pmjs-game-noengine-');
  writeGame(noEngine, { rpgCore: null, pixi: null });
  const found = inspectGame(noEngine, registry);
  assert.equal(found.engine, 'unknown');
  assert.throws(() => readPluginManifest(empty), /plugin manifest not found/);
});

test('adapter registry rejects duplicates and malformed entries', async () => {
  const { loadAdapterRegistry } = await loadInspect();
  const dir = temporaryDirectory('pmjs-registry-');
  const dupe = path.join(dir, 'dupe.json');
  fs.writeFileSync(dupe, JSON.stringify({ adapters: [
    { plugins: ['A'], modules: ['a.js'] },
    { plugins: ['A'], modules: ['b.js'] },
  ] }));
  assert.throws(() => loadAdapterRegistry(dupe), /duplicate adapter plugin name/);
  const bad = path.join(dir, 'bad.json');
  fs.writeFileSync(bad, JSON.stringify({ adapters: [{ plugins: ['A'] }] }));
  assert.throws(() => loadAdapterRegistry(bad), /requires nonempty plugins and modules arrays/);
  const good = path.join(__dirname, '..', 'profiles', 'plugin-adapters.json');
  assert.ok(loadAdapterRegistry(good).length > 0);
});


test('canonical identities match and detect registry collisions', async () => {
  const { resolveAdapters, loadAdapterRegistry } = await loadInspect();
  const adapters = [{ plugins: ['YEP_CoreEngine'], modules: ['adapter.js'] }];
  for (const name of ['YEP_CoreEngine', 'yep_coreengine', 'YEP_CoreEngine.js']) {
    assert.equal(resolveAdapters(adapters, [name], 'mv').length, 1);
  }
  assert.equal(resolveAdapters(adapters, ['folder/yep_coreengine.js'], 'mv').length, 0);
  assert.equal(resolveAdapters(adapters, ['folder/yep_coreengine.js']).length, 0);
  assert.equal(resolveAdapters(adapters, ['folder/yep_coreengine.js'], 'mz').length, 1);
  assert.equal(resolveAdapters([{ plugins: ['folder/Example.js'], modules: ['adapter.js'] }], ['Example'], 'mz').length, 1);
  const dir = temporaryDirectory('pmjs-identities-');
  const file = path.join(dir, 'registry.json');
  fs.writeFileSync(file, JSON.stringify({ adapters: [adapters[0], { plugins: ['yep_coreengine.js'], modules: ['other.js'] }] }));
  assert.throws(() => loadAdapterRegistry(file), /YEP_CoreEngine and yep_coreengine.js/);
  fs.writeFileSync(file, JSON.stringify({ adapters: [adapters[0], { plugins: ['folder/yep_coreengine'], modules: ['other.js'] }] }));
  assert.equal(loadAdapterRegistry(file, 'mv').length, 2);
});

test('inspection reports matched names and warns on canonical manifest collisions', async t => {
  const { inspectGame } = await loadInspect();
  const dir = temporaryDirectory('pmjs-collision-');
  writeGame(dir, { pluginsJs: 'var $plugins = ' + JSON.stringify([
    { name: 'yed_tiled.js', status: true }, { name: 'YED_Tiled', status: true },
    { name: 'Unknown.js', status: true }]) });
  const warnings = [];
  t.mock.method(console, 'warn', message => warnings.push(message));
  const result = inspectGame(dir, path.join(__dirname, '../profiles/plugin-adapters.json'));
  assert.deepEqual(result.matchedAdapters, []);
  assert.deepEqual(result.selectablePlugins, ['Unknown.js']);
  assert.deepEqual(result.unmatchedEnabledPlugins, ['Unknown.js']);
  assert.match(warnings[0], /yed_tiled.js, YED_Tiled/);
});


test('MZ inspection uses basename identities for matching, unknown names and collisions', async t => {
  const { inspectGame } = await loadInspect();
  const dir = temporaryDirectory('pmjs-mz-identities-');
  const plugins = [{ name: 'folder/Example.js', status: true }, { name: 'other/Missing.js', status: true }];
  writeGame(dir, { rpgCore: null, pixi: "PIXI.VERSION = '5.3.12';", pluginsJs: 'var $plugins = ' + JSON.stringify(plugins) + ';' });
  fs.writeFileSync(path.join(dir, 'js/rmmz_core.js'), '// RPG Maker MZ v1.8.1\n');
  const registry = path.join(dir, 'registry.json');
  fs.writeFileSync(registry, JSON.stringify({ adapters: [{ plugins: ['Example'], modules: ['adapter.js'] }] }));
  const report = inspectGame(dir, registry);
  assert.equal(report.engine, 'mz');
  assert.deepEqual(report.matchedAdapters, [{ plugin: 'Example', modules: ['adapter.js'] }]);
  assert.deepEqual(report.unmatchedEnabledPlugins, ['other/Missing.js']);
  const warnings = [];
  t.mock.method(console, 'warn', message => warnings.push(message));
  plugins.push({ name: 'another/EXAMPLE', status: true });
  fs.writeFileSync(path.join(dir, 'js/plugins.js'), 'var $plugins = ' + JSON.stringify(plugins) + ';');
  const collision = inspectGame(dir, registry);
  assert.deepEqual(collision.matchedAdapters, []);
  assert.deepEqual(collision.selectablePlugins, ['other/Missing.js']);
  assert.deepEqual(collision.unmatchedEnabledPlugins, ['other/Missing.js']);
  assert.match(warnings[0], /folder\/Example.js, another\/EXAMPLE/);
});

test('build identity agrees with runtime tracking for MV and MZ names', async () => {
  const { pluginIdentity } = await loadInspect();
  const { loadPmjsRuntime } = require('./helpers/runtime-context.cjs');
  for (const engine of ['mv', 'mz']) {
    for (const name of ['YEP_CoreEngine', 'yep_coreengine.js', 'folder/Example.JS']) {
      const runtime = loadPmjsRuntime({ PMJS_RUNTIME_ENGINE: engine });
      runtime.PMJS.plugins.snapshotEffectiveManifest([{ name, status: true }]);
      assert.equal(runtime.PMJS.plugins.dump().guest[0].key, pluginIdentity(name, engine));
    }
  }
});
