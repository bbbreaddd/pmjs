'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const native = require(path.resolve(process.argv[2]));
native.initialize({gameRoot:path.resolve(process.argv[3]),width:4,height:4,windowTitle:'Tile shadow ownership',imageWarmCacheBytes:0});
native.images.memory(0);
const before = native.images.memory(0).liveCount;
const layer = native.render.createTileLayer(new Float32Array([0,0,1,1,2,2,0,0,-1]),[]);
const schema = native.scene.schema, values = new Float32Array(schema.valueStride);
values.set([1,0,0,1,0,0,1]);
native.beginFrame(); native.render.quad(0,0,4,4,1,1,1,1);
native.scene.submit(schema.version,new Uint32Array([4,0xffffffff,layer,0xffffff,0,8,0]),values,1);
native.renderFrame();
const pixels = native.canvas.captureSceneRawPremultiplied();
assert.equal(pixels[0],255);
assert.ok(pixels[(1*4+1)*4] >= 127 && pixels[(1*4+1)*4] <= 128);
assert.equal(pixels[(1*4+1)*4+3],255);
native.render.releaseTileLayer(layer); native.beginFrame(); native.renderFrame();
assert.equal(native.images.memory(0).liveCount,before,'shadow image lifetime belongs to retained tile geometry');
