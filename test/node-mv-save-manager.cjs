'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const native = require(path.resolve(process.argv[2])), engine = native.mvEngine;
const { fixture } = require('./helpers/mv-session-fixture.cjs');
const { temporaryDirectory } = require('./helpers/temp.cjs');
const { createStorage } = require('../runner/storage.cjs');
const { createScriptRuntime } = require('../runner/mv-script-runtime.cjs');
const { installStorage } = require('../runner/native-storage.cjs');
const { installSaveManager } = require('../runner/native-save-manager.cjs');

test('save hooks preserve native state, plugin fields, cycles and actor identity', t => {
  const data = fixture([]), session = engine.create(data);
  t.after(() => engine.dispose(session));
  const runtime = createScriptRuntime(engine, session), scope = runtime.scope;
  scope.$dataSystem = data.system;
  scope.console = console;
  scope.DataManager.createGameObjects = () => engine.newGame(session);
  scope.Graphics = { frameCount: 123 };
  scope.AudioManager = { saveBgm: () => ({}), saveBgs: () => ({}), playBgm() {}, playBgs() {} };
  installStorage(runtime, native, createStorage(temporaryDirectory('manager-save-')));
  installSaveManager(runtime, engine, session);
  engine.newGame(session);
  const actor = scope.$gameActors.actor(1);
  actor.pluginState = { score: 17, owner: actor };
  scope.$gameSystem.pluginActor = actor;
  scope.$gameVariables.setValue(3, 42);
  const make = scope.DataManager.makeSaveContents, extract = scope.DataManager.extractSaveContents;
  let saves = 0, loads = 0;
  scope.DataManager.makeSaveContents = function() { ++saves; const contents = make.call(this); contents.plugin = { actor, shared: actor.pluginState }; return contents; };
  scope.DataManager.extractSaveContents = function(contents) { extract.call(this, contents); ++loads; scope.loadedPlugin = contents.plugin; };
  assert.equal(scope.DataManager.saveGame(1), true);
  assert.equal(scope.DataManager.loadSavefileInfo(1).playtime, '00:00:02');
  assert.equal(scope.DataManager.isAnySavefileExists(), true);
  scope.$gameVariables.setValue(3, 9); actor.pluginState.score = 99;
  assert.equal(scope.DataManager.loadGame(1), true);
  const restored = scope.$gameActors.actor(1);
  assert.equal(scope.$gameVariables.value(3), 42);
  assert.equal(restored.pluginState.score, 17);
  assert.equal(restored.pluginState.owner, restored);
  assert.equal(scope.$gameSystem.pluginActor, restored);
  assert.equal(scope.loadedPlugin.actor, restored);
  assert.equal(scope.loadedPlugin.shared, restored.pluginState);
  assert.equal(saves, 1); assert.equal(loads, 1);
  const write = scope.StorageManager.save;
  scope.StorageManager.save = function(id, json) { if (id === 0) throw new Error('metadata write failed'); return write.call(this, id, json); };
  scope.console = { error() {}, warn() {} };
  restored.pluginState.score = 88;
  assert.equal(scope.DataManager.saveGame(1), false);
  scope.StorageManager.save = write;
  assert.equal(scope.DataManager.loadGame(1), true);
  assert.equal(scope.$gameActors.actor(1).pluginState.score, 17, 'metadata failure restores the previous slot');
});
